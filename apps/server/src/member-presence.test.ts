import { afterEach, expect, it } from 'vitest';
import { PgliteDatabase } from './test-support.js';
import { memberPresenceSql } from './member-presence.js';
let db: PgliteDatabase;
afterEach(async () => db?.close());
it('reads joined-session presence from its existing connection, and clears on disconnect or revoked credentials', async () => {
  db = new PgliteDatabase();
  await db.query(`CREATE TABLE rooms_mcp_delivery(member_id text,mechanism text,stream_id text,failure text,credential_hash text,created_at timestamptz DEFAULT now());
    CREATE TABLE rooms_mcp_tokens(hash text,revoked_at timestamptz,expires_at timestamptz,client_id text,identity_id text);
    CREATE TABLE rooms_mcp_connections(client_id text,identity_id text,revoked_at timestamptz);
    CREATE TABLE live_outputs(agent_id text,kind text,body jsonb,updated_at timestamptz DEFAULT now());
    INSERT INTO rooms_mcp_delivery(member_id,mechanism,credential_hash) VALUES('claude','local','token');
    INSERT INTO rooms_mcp_tokens VALUES('token',NULL,now()+interval '1 hour','client','owner');
    INSERT INTO rooms_mcp_connections VALUES('client','owner',NULL);
    INSERT INTO live_outputs(agent_id,kind,body) VALUES('claude','presence','{"status":"offline"}'),('helper','presence','{"status":"online","held":true}');`);
  const presence = async (id = 'claude') => (await db.query<{body: {status:string; held:boolean}}>(memberPresenceSql('$1'), [id])).rows[0]?.body;
  expect(await presence()).toMatchObject({status:'offline',held:false});
  await db.query("UPDATE rooms_mcp_delivery SET stream_id='connected'");
  expect(await presence()).toMatchObject({status:'online',held:true});
  await db.query("UPDATE rooms_mcp_delivery SET stream_id=NULL");
  expect(await presence()).toMatchObject({status:'offline',held:false});
  await db.query("UPDATE rooms_mcp_delivery SET stream_id='connected'; UPDATE rooms_mcp_tokens SET revoked_at=now()");
  expect(await presence()).toMatchObject({status:'offline',held:false});
  await db.query("UPDATE rooms_mcp_tokens SET revoked_at=NULL; UPDATE rooms_mcp_connections SET revoked_at=now()");
  expect(await presence()).toMatchObject({status:'offline',held:false});
  await db.query("UPDATE rooms_mcp_connections SET revoked_at=NULL; UPDATE rooms_mcp_tokens SET expires_at=now()-interval '2 hours'");
  expect(await presence()).toMatchObject({status:'online',held:true});
  expect(await presence('helper')).toEqual({status:'online',held:true});
});
